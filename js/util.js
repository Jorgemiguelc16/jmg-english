let toastTimer = null;
function toast(html, ms = 3200) {
  html = `<span class="toast-dot"></span>${html}`;
  const el = $('#toast');
  el.innerHTML = html;
  el.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove('show'), ms);
}

